import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { defaultConfig, simulateCandidate } from '../math/trajectory';
import { fitShotMap, evaluatePolynomial } from '../math/polynomial';
import { generatedCoefficients } from '../math/generatedCoefficients';
import type { TrajectoryCandidate } from '../math/types';

// Experimental fixed-pitch maps. Only the 4–8 m far domain is fitted; close shots keep the original map.
const transitionStartMeters = 4.9;
const transitionFullMeters = 5.5;
const profiles = [63, 61].map(angle => {
  const hood = defaultConfig.hoodSlope * angle + defaultConfig.hoodIntercept;
  const samples: TrajectoryCandidate[] = [];
  for (let d = 4; d <= 8.001; d += 0.25) {
    for (let r = -2.5; r <= 2.501; r += 0.25) {
      let low = 0, high = 3;
      const residual = (t: number) => Math.tan(angle * Math.PI / 180) * (d - r * t)
        - (defaultConfig.targetHeightMeters - defaultConfig.shooterExitHeightMeters)
        - 0.5 * defaultConfig.gravityMps2 * t * t;
      if (residual(high) >= 0) continue;
      for (let i = 0; i < 48; i++) {
        const mid = (low + high) / 2;
        if (residual(mid) > 0) low = mid; else high = mid;
      }
      const speed = (d / ((low + high) / 2) - r) / Math.cos(angle * Math.PI / 180);
      if (speed < defaultConfig.minExitSpeedMps || speed > defaultConfig.maxExitSpeedMps) continue;
      const candidate = simulateCandidate(defaultConfig, { distanceMeters: d, radialVelocityMps: r }, hood, speed);
      if (candidate) samples.push(candidate);
    }
  }
  const fit = fitShotMap(samples);
  let accepted = 0, checked = 0;
  const stationary = [];
  // Finer than the training grid, including points between training inputs.
  for (let d = 4; d <= 8.001; d += 0.05) {
    for (let r = -2.5; r <= 2.501; r += 0.1) {
      const input = { distanceMeters: d, radialVelocityMps: r };
      let blend = Math.min(1, Math.max(0, (d - transitionStartMeters) / (transitionFullMeters - transitionStartMeters)));
      blend = blend * blend * (3 - 2 * blend);
      const h0 = evaluatePolynomial(generatedCoefficients.hood, input);
      const r0 = evaluatePolynomial(generatedCoefficients.roller, input);
      const h = h0 + blend * (hood - h0);
      const rpm = r0 + blend * (evaluatePolynomial(fit.rollerCoefficients, input) - r0);
      const speed = (Math.abs(rpm) - defaultConfig.rollerIntercept) / defaultConfig.rollerSlope;
      const valid = h >= defaultConfig.minHoodRot && h <= defaultConfig.maxHoodRot
        && speed > 0 && speed <= defaultConfig.maxExitSpeedMps
        && simulateCandidate(defaultConfig, input, h, speed) !== null;
      checked++; if (valid) accepted++;
    }
  }
  for (const d of [4, 4.5, 4.9, 5, 5.5, 6, 7, 8]) {
    const input = { distanceMeters: d, radialVelocityMps: 0 };
    let blend = Math.min(1, Math.max(0, (d - transitionStartMeters) / (transitionFullMeters - transitionStartMeters))); blend = blend * blend * (3 - 2 * blend);
    const h0 = evaluatePolynomial(generatedCoefficients.hood, input);
    const r0 = evaluatePolynomial(generatedCoefficients.roller, input);
    const h = h0 + blend * (hood - h0);
    const rps = r0 + blend * (evaluatePolynomial(fit.rollerCoefficients, input) - r0);
    const speed = (Math.abs(rps) - defaultConfig.rollerIntercept) / defaultConfig.rollerSlope;
    stationary.push({ distance: d, hood: h, rpsBeforeTrim: rps,
      feasible: simulateCandidate(defaultConfig, input, h, speed) !== null });
  }
  return { angle, hood, coefficients: fit.rollerCoefficients, samples: samples.length,
    maxRpsFitError: fit.maxRollerResidualRps, accepted, checked, stationary };
});
const java = `package frc.robot.constants;

/** Experimental far-Hub maps. Generated by npm run generate:far-trials; 4–8 m, radial +/-2.5 m/s. */
public final class GeneratedFarShotTrials {
    public static final double TRANSITION_START_METERS = ${transitionStartMeters};
    public static final double TRANSITION_FULL_METERS = ${transitionFullMeters};
    private GeneratedFarShotTrials() {}
    public static double hood(int profile) {
        return profile == 2 ? ${profiles[1].hood} : ${profiles[0].hood};
    }
    private static final double[][] RPS = {
        { ${profiles[0].coefficients.join(', ')} },
        { ${profiles[1].coefficients.join(', ')} }
    };
    public static double rollerRps(int profile, double distance, double radial) {
        double[] c = RPS[profile == 2 ? 1 : 0];
        return c[0] + c[1]*distance + c[2]*radial + c[3]*distance*distance
            + c[4]*distance*radial + c[5]*radial*radial;
    }
}
`;
writeFileSync(resolve('../../src/main/java/frc/robot/constants/GeneratedFarShotTrials.java'), java);
writeFileSync(resolve('far-shot-trial-report.json'), JSON.stringify({
  note: 'Experimental gravity-only model validation before global RPS trim; no field accuracy claim. Grid acceptance includes physically unreachable inputs. Sideways motion and tilt require runtime validation.',
  transitionStartMeters, transitionFullMeters, profiles,
}, null, 2) + '\n');
